// Generates client/src/styles/tokens.css from design/tokens.json.
//   node design/build-tokens.mjs           write the CSS
//   node design/build-tokens.mjs --check   exit 1 if the CSS is out of date
//
// Themes: light by default; dark when <html data-theme="dark">, or when the
// system is dark and the user has not forced light (data-theme="system" or
// no attribute). The toggle in the navbar sets data-theme (lib/theme.js).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const t = JSON.parse(readFileSync(new URL('design/tokens.json', root)));
const out = new URL('client/src/styles/tokens.css', root);

const ref = (v) => (v.startsWith('{') ? `var(--p-${v.slice(1, -1)})` : v);
const block = (entries, indent = '  ') => entries.map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');
const semantic = (mode) => Object.entries(t.semantic[mode]).map(([k, v]) => [k, ref(v)]);
const codes = t.boroughCodes;

const lightOnly = [
  ...Object.entries(t.primitive).map(([k, v]) => [`p-${k}`, v]),
  ...Object.entries(t.borough).map(([name, v]) => [`borough-${codes[name].toLowerCase()}`, ref(v)]),
  ['borough-text', ref(t.boroughText)],
  ...Object.entries(t.radius).map(([k, v]) => [`r-${k}`, `${v}px`]),
  ['radius', `${t.radius.control}px`], // legacy name used by styles/legacy.css
  ...t.space.map((v, i) => [`space-${i + 1}`, `${v}px`]),
  ...Object.entries(t.motion).map(([k, v]) => [`motion-${k}`, typeof v === 'number' ? `${v}ms` : v]),
];

const css = `/* GENERATED by design/build-tokens.mjs from design/tokens.json. Do not edit by hand. */

:root {
${block(lightOnly)}
${block(semantic('light'))}
  color-scheme: light;
}

:root[data-theme="dark"] {
${block(semantic('dark'))}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(semantic('dark'), '    ')}
    color-scheme: dark;
  }
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch {}
  if (current !== css) { console.error('tokens.css is out of date: run node design/build-tokens.mjs'); process.exit(1); }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(out, css);
  console.log(`wrote ${out.pathname.split('/part3/')[1]} (${lightOnly.length} base + ${Object.keys(t.semantic.light).length} semantic tokens per theme)`);
}
