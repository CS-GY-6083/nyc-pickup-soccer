// Downloads NYC Parks open data and writes db/open_data_fields.sql: every
// active soccer field in the city, added after the 12 hand-entered seed
// fields. db/reset.sh loads that file (skip it with OPEN_DATA_FIELDS=0).
//
//   node db/open-data/build_fields.mjs
//
// Needs internet only when you run it; the generated SQL is committed, so
// resetting the database works offline. The rules (which rows count,
// names, surfaces, hours, de-duplication) are in transform.mjs.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { buildFields, toSql } from './transform.mjs';

const API = 'https://data.cityofnewyork.us/resource';
const FACILITIES = 'qnem-b8re'; // NYC Parks Athletic Facilities
const PROPERTIES = 'enfh-gkve'; // NYC Parks Properties
const here = (p) => fileURLToPath(new URL(p, import.meta.url));

async function socrata(dataset, params) {
  const url = new URL(`${API}/${dataset}.json`);
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v);
  const res = await fetch(url, { headers: { Accept: 'application/json' } });
  if (!res.ok) throw new Error(`${dataset}: HTTP ${res.status}`);
  return res.json();
}

/** The 12 seed fields (name, lat, lng), read from the Field INSERT in seed.sql. */
async function seedFields() {
  const sql = await readFile(here('../seed.sql'), 'utf8');
  const row = /^\s*\(\s*\d+,\s*'((?:[^']|'')*)',.*?,\s*(4\d\.\d+),\s*(-7\d\.\d+)\)/;
  return sql
    .split('\n')
    .map((line) => row.exec(line))
    .filter(Boolean)
    .map((m) => ({ name: m[1].replace(/''/g, "'"), lat: Number(m[2]), lng: Number(m[3]) }));
}

const [facilities, properties, existing] = await Promise.all([
  socrata(FACILITIES, {
    $select: 'system,gispropnum,borough,field_number,surface_type,field_lighted,featurestatus,regulation_soccer,nonregulation_soccer,multipolygon',
    $where: "featurestatus = 'Active' AND (regulation_soccer = true OR nonregulation_soccer = true)",
    $limit: '50000',
  }),
  socrata(PROPERTIES, { $select: 'gispropnum,signname,location', $limit: '50000' }),
  seedFields(),
]);
if (existing.length !== 12) throw new Error(`Expected 12 seed fields in seed.sql, found ${existing.length}`);

// Parks whose property number is missing from the Properties dataset,
// named from where their fields are (checked on the map).
const PARK_OVERRIDES = {
  BT15: { name: 'Bush Terminal Piers Park', location: 'Sunset Park waterfront, 43 St to 51 St' },
};

const parks = new Map(properties.map((p) => [p.gispropnum, { name: p.signname, location: p.location }]));
for (const [id, park] of Object.entries(PARK_OVERRIDES)) if (!parks.has(id)) parks.set(id, park);
const { fields, skipped } = buildFields(facilities, parks, existing);

const today = new Date().toISOString().slice(0, 10);
const header = `-- =====================================================================
-- NYC Pickup Soccer System: real NYC soccer fields from NYC Open Data
-- GENERATED by db/open-data/build_fields.mjs on ${today}. Do not edit by
-- hand; re-run the script to refresh it.
--
-- Sources (NYC Open Data, free to use under the NYC Open Data Terms of Use):
--   NYC Parks Athletic Facilities  https://data.cityofnewyork.us/d/${FACILITIES}
--   NYC Parks Properties           https://data.cityofnewyork.us/d/${PROPERTIES}
--
-- ${fields.length} active fields marked for regulation or non-regulation soccer.
-- Left out: ${skipped.nearSeedField} within 75 m of a hand-entered seed field (same pitch),
-- ${skipped.noGeometry} without a location, ${skipped.outsideNyc} outside the NYC box, ${skipped.unknownSurface} with another surface.
--   name      "<park> Soccer Field <field number>" (park name from Properties)
--   location  park name + its location text
--   surface   Natural -> Natural Grass; Synthetic -> Synthetic Turf; Asphalt
--   lat/lng   centre of the field's outline
--   hours     not in the data; same rules as seed.sql: lit 07:00-22:00 daily,
--             unlit 08:00-17:00 daily, unlit grass closed Mondays
--
-- Loaded by reset.sh after seed.sql (ids continue after the seed's 12).
-- These fields have no games, bookings or photos of their own.
-- =====================================================================

BEGIN;

`;
await writeFile(here('../open_data_fields.sql'), `${header}${toSql(fields)}\nCOMMIT;\n`);
console.log(`Wrote db/open_data_fields.sql: ${fields.length} fields. Skipped:`, skipped);
