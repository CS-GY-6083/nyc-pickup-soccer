-- Organizers book a public NYC soccer field and post a pickup game on
-- it; players sign up for open games; admins approve field bookings.
-- All TIMESTAMP columns hold New York local time; nyc_now() below gives
-- the current New York time on any server.
--
-- Run:  psql -d nyc_fields -f create_tables.sql
-- The script is re-runnable: it drops existing tables first.
--
-- Updated for Part 3 (the spec asks to merge extra tables and attributes
-- back into Part 2): the GameRating table, and PickupGame.delayed /
-- delay_note. The full Part 3 schema is part3/db/schema.sql.
-- =====================================================================

DROP TABLE IF EXISTS GameRating, GameRegistration, PickupGame, Reservation,
                     FieldClosure, FieldOperatingHours, Field, Users CASCADE;

-- Needed so the Reservation exclusion constraint can combine an equality
-- test on field_id (a plain integer) with a time-range overlap test.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Current New York local time, whatever time zone the server or session
-- uses. Used for column defaults and as "now" in the queries.
CREATE OR REPLACE FUNCTION nyc_now() RETURNS TIMESTAMP
    LANGUAGE sql STABLE
    AS $$ SELECT now() AT TIME ZONE 'America/New_York' $$;


-- ---------------------------------------------------------------------
-- Users
--   player    : signs up for pickup games
--   organizer : books fields and hosts pickup games (can also play)
--   admin     : approves or rejects field bookings, records closures
-- Named "Users" because USER is a reserved word in PostgreSQL.
-- Emails are unique regardless of capitals (see uq_users_email below).
-- ---------------------------------------------------------------------
CREATE TABLE Users (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    email          VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL DEFAULT 'player',
    CONSTRAINT chk_users_role
        CHECK (role IN ('player', 'organizer', 'admin')),
    -- one '@', no spaces, and a dot in the domain part (e.g. a@b.com)
    CONSTRAINT chk_users_email
        CHECK (email ~ '^[^@[:space:]]+@[^@[:space:].][^@[:space:]]*\.[^@[:space:]]+$')
);


-- ---------------------------------------------------------------------
-- Field: public NYC soccer fields where pickup games are played
-- ---------------------------------------------------------------------
CREATE TABLE Field (
    field_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    borough       VARCHAR(20)  NOT NULL,
    location      VARCHAR(255) NOT NULL,
    surface_type  VARCHAR(30)  NOT NULL,
    CONSTRAINT chk_field_borough
        CHECK (borough IN ('Manhattan', 'Brooklyn', 'Queens', 'Bronx', 'Staten Island')),
    CONSTRAINT chk_field_surface
        CHECK (surface_type IN ('Natural Grass', 'Synthetic Turf', 'Asphalt'))
);


-- ---------------------------------------------------------------------
-- FieldOperatingHours: when a field is open for games (weak entity of
-- Field). day_of_week uses PostgreSQL's EXTRACT(DOW ...) numbering:
-- 0 = Sunday, 1 = Monday, ..., 6 = Saturday. No row = closed that day.
-- ---------------------------------------------------------------------
CREATE TABLE FieldOperatingHours (
    field_id     INT      NOT NULL,
    day_of_week  SMALLINT NOT NULL,
    open_time    TIME     NOT NULL,
    close_time   TIME     NOT NULL,
    PRIMARY KEY (field_id, day_of_week),
    CONSTRAINT fk_hours_field
        FOREIGN KEY (field_id) REFERENCES Field (field_id) ON DELETE CASCADE,
    CONSTRAINT chk_hours_day
        CHECK (day_of_week BETWEEN 0 AND 6),
    CONSTRAINT chk_hours_order
        CHECK (close_time > open_time)
);


-- ---------------------------------------------------------------------
-- FieldClosure: periods when a field cannot host games (repairs,
-- reseeding, tournaments), recorded by an admin
-- ---------------------------------------------------------------------
CREATE TABLE FieldClosure (
    closure_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id    INT          NOT NULL,
    start_time  TIMESTAMP    NOT NULL,
    end_time    TIMESTAMP    NOT NULL,
    reason      VARCHAR(255) NOT NULL,
    created_by  INT          NOT NULL,
    CONSTRAINT fk_closure_field
        FOREIGN KEY (field_id)   REFERENCES Field (field_id) ON DELETE CASCADE,
    CONSTRAINT fk_closure_creator
        FOREIGN KEY (created_by) REFERENCES Users (user_id),
    CONSTRAINT chk_closure_order
        CHECK (end_time > start_time)
);


-- ---------------------------------------------------------------------
-- Reservation: an organizer's booking of a field for a pickup game.
-- An admin approves or rejects it; the organizer can cancel it.
--   pending -> approved | rejected;  pending/approved -> cancelled
-- ---------------------------------------------------------------------
CREATE TABLE Reservation (
    reservation_id    INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INT          NOT NULL,
    field_id          INT          NOT NULL,
    start_time        TIMESTAMP    NOT NULL,
    end_time          TIMESTAMP    NOT NULL,
    status            VARCHAR(20)  NOT NULL DEFAULT 'pending',
    requested_at      TIMESTAMP    NOT NULL DEFAULT nyc_now(),
    reviewed_by       INT,
    reviewed_at       TIMESTAMP,
    rejection_reason  VARCHAR(255),
    CONSTRAINT fk_reservation_user
        FOREIGN KEY (user_id)     REFERENCES Users (user_id),
    CONSTRAINT fk_reservation_field
        FOREIGN KEY (field_id)    REFERENCES Field (field_id),
    CONSTRAINT fk_reservation_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES Users (user_id),
    CONSTRAINT chk_reservation_status
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    CONSTRAINT chk_reservation_order
        CHECK (end_time > start_time),
    -- A game slot must be booked before it starts.
    CONSTRAINT chk_reservation_future
        CHECK (start_time > requested_at),
    -- Pickup-game slot rules: a game slot lasts 1 to 3 hours and starts
    -- and ends on the same day.
    CONSTRAINT chk_reservation_length
        CHECK (end_time - start_time BETWEEN INTERVAL '1 hour' AND INTERVAL '3 hours'),
    CONSTRAINT chk_reservation_same_day
        CHECK (start_time::date = end_time::date),
    -- Pending bookings have no reviewer; approved/rejected ones must.
    CONSTRAINT chk_reservation_review
        CHECK (   (status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL)
               OR (status IN ('approved', 'rejected')
                   AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
               OR  status = 'cancelled'),
    -- A review records both who reviewed and when, or neither.
    CONSTRAINT chk_reservation_reviewer_pair
        CHECK ((reviewed_by IS NULL) = (reviewed_at IS NULL)),
    CONSTRAINT chk_reservation_reviewed_after_request
        CHECK (reviewed_at IS NULL OR reviewed_at >= requested_at),
    -- A rejection reason is given exactly when a booking is rejected.
    CONSTRAINT chk_reservation_rejection_reason
        CHECK ((status = 'rejected') = (rejection_reason IS NOT NULL)),
    -- No two pickup games can hold APPROVED bookings on the same field at
    -- overlapping times. tsrange is half-open [start, end), so back-to-back
    -- games (09:00-11:00 and 11:00-13:00) are allowed.
    CONSTRAINT excl_reservation_no_overlap
        EXCLUDE USING gist (field_id WITH =, tsrange(start_time, end_time) WITH &&)
        WHERE (status = 'approved')
);


-- ---------------------------------------------------------------------
-- PickupGame: a game posted by an organizer on a field booking.
-- Each game uses exactly one booking, and each booking hosts at most one
-- game (UNIQUE reservation_id). The game's field, date and time come from
-- its booking.
--   scheduled : open for sign-ups (its booking may still be pending)
--   completed : played
--   cancelled : called off, or its booking was rejected/cancelled
-- delayed / delay_note (added in Part 3): "on time" or "delayed", like a
-- flight's status. A delayed game still goes ahead, so it is a flag
-- beside the status rather than another status value.
-- ---------------------------------------------------------------------
CREATE TABLE PickupGame (
    game_id         INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id    INT         NOT NULL,
    reservation_id  INT         NOT NULL UNIQUE,
    format          VARCHAR(10) NOT NULL,
    skill_level     VARCHAR(20) NOT NULL,
    max_players     SMALLINT    NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'scheduled',
    delayed         BOOLEAN     NOT NULL DEFAULT false,
    delay_note      VARCHAR(200),
    CONSTRAINT fk_game_organizer
        FOREIGN KEY (organizer_id)   REFERENCES Users (user_id),
    CONSTRAINT fk_game_reservation
        FOREIGN KEY (reservation_id) REFERENCES Reservation (reservation_id),
    CONSTRAINT chk_game_format
        CHECK (format IN ('5v5', '6v6', '7v7', '8v8', '9v9', '11v11')),
    CONSTRAINT chk_game_skill
        CHECK (skill_level IN ('beginner', 'intermediate', 'advanced', 'all levels')),
    -- Enough room for two full teams (e.g. 7v7 needs at least 14), max 30.
    CONSTRAINT chk_game_max_players
        CHECK (max_players >= 2 * split_part(format, 'v', 1)::int
               AND max_players <= 30),
    CONSTRAINT chk_game_status
        CHECK (status IN ('scheduled', 'completed', 'cancelled')),
    -- A note only explains a delay: none while the game is on time.
    CONSTRAINT chk_game_delay_note
        CHECK (delay_note IS NULL OR delayed)
);


-- ---------------------------------------------------------------------
-- GameRegistration: a player's sign-up for a pickup game.
-- Leaving a game (or the game being called off) sets
-- registration_status = 'cancelled' instead of deleting the row, so the
-- sign-up history is kept.
-- ---------------------------------------------------------------------
CREATE TABLE GameRegistration (
    game_id              INT         NOT NULL,
    user_id              INT         NOT NULL,
    joined_at            TIMESTAMP   NOT NULL DEFAULT nyc_now(),
    registration_status  VARCHAR(20) NOT NULL DEFAULT 'registered',
    PRIMARY KEY (game_id, user_id),
    CONSTRAINT fk_registration_game
        FOREIGN KEY (game_id) REFERENCES PickupGame (game_id) ON DELETE CASCADE,
    CONSTRAINT fk_registration_user
        FOREIGN KEY (user_id) REFERENCES Users (user_id),
    CONSTRAINT chk_registration_status
        CHECK (registration_status IN ('registered', 'cancelled'))
);


-- ---------------------------------------------------------------------
-- GameRating (added in Part 3): a player's rating (1-5 stars) and
-- optional comment on a pickup game they played. The composite foreign
-- key to GameRegistration means only someone who signed up for the game
-- can rate it, and only once (primary key). The trigger below adds the
-- rules that span several tables (a CHECK constraint cannot): the
-- sign-up was not cancelled, and the game actually took place.
-- ---------------------------------------------------------------------
CREATE TABLE GameRating (
    game_id   INT           NOT NULL,
    user_id   INT           NOT NULL,
    rating    SMALLINT      NOT NULL,
    comment   VARCHAR(1000),
    rated_at  TIMESTAMP     NOT NULL DEFAULT nyc_now(),
    PRIMARY KEY (game_id, user_id),
    CONSTRAINT fk_rating_registration
        FOREIGN KEY (game_id, user_id)
        REFERENCES GameRegistration (game_id, user_id) ON DELETE CASCADE,
    CONSTRAINT chk_rating_range
        CHECK (rating BETWEEN 1 AND 5),
    -- An empty comment is stored as NULL rather than ''.
    CONSTRAINT chk_rating_comment
        CHECK (comment IS NULL OR length(btrim(comment)) > 0)
);

-- A rating is only allowed when the player is still registered for the
-- game, the field booking was approved, the game was not cancelled, and
-- it is over (marked completed, or its end time has passed).
CREATE OR REPLACE FUNCTION trg_rating_eligible() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM GameRegistration x
        JOIN PickupGame g  ON g.game_id = x.game_id
        JOIN Reservation r ON r.reservation_id = g.reservation_id
        WHERE x.game_id = NEW.game_id
          AND x.user_id = NEW.user_id
          AND x.registration_status = 'registered'
          AND r.status = 'approved'
          AND g.status <> 'cancelled'
          AND (g.status = 'completed' OR r.end_time <= nyc_now())
    ) THEN
        RAISE EXCEPTION 'Player % cannot rate game %', NEW.user_id, NEW.game_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'chk_rating_eligible';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER rating_eligible
    BEFORE INSERT OR UPDATE OF game_id, user_id ON GameRating
    FOR EACH ROW EXECUTE FUNCTION trg_rating_eligible();


-- ---------------------------------------------------------------------
-- Indexes
-- (PostgreSQL indexes primary keys and UNIQUE columns automatically,
--  but not foreign keys.)
-- ---------------------------------------------------------------------
-- One account per email address, ignoring capitals:
-- 'Maria.Lopez@example.com' counts as the same as 'maria.lopez@example.com'.
CREATE UNIQUE INDEX uq_users_email       ON Users (lower(email));

-- Common pickup-game lookups
CREATE INDEX idx_field_borough_surface   ON Field (borough, surface_type);
CREATE INDEX idx_reservation_field_time  ON Reservation (field_id, start_time);
CREATE INDEX idx_reservation_user        ON Reservation (user_id);
CREATE INDEX idx_reservation_status_time ON Reservation (status, start_time);
CREATE INDEX idx_closure_field           ON FieldClosure (field_id);
CREATE INDEX idx_game_organizer          ON PickupGame (organizer_id);
CREATE INDEX idx_registration_user       ON GameRegistration (user_id);
CREATE INDEX idx_rating_user             ON GameRating (user_id);
